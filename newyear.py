@router.message(Command("advent", "адвент", "календарь"))
async def cmd_advent(message: Message):
    today = dt.date.today()
    if not (today.month == 12 and 1 <= today.day <= 31):
        await message.reply(
            "Адвент-календарь работает с 1 по 31 декабря. "
            "До Нового года осталось — глянь «до нового года»! ⏳"
        )
        return
    box = ADVENT.get(today.day)
    # если день не в списке — берём случайное окошко из доступных
    if box is None:
        import random

        box = ADVENT[random.choice(list(ADVENT.keys()))]
    await message.reply(
        f"🎄 Адвент-календарь • {today.day} декабря\n\n{box}"
    )


@router.message(Command("countdown", "до_нового_года", "таймер"))
async def cmd_countdown(message: Message):
    now = dt.datetime.now()
    ny = dt.datetime(now.year + 1, 1, 1)
    delta = ny - now
    days = delta.days
    hours, rem = divmod(delta.seconds, 3600)
    minutes, seconds = divmod(rem, 60)
    await message.reply(
        f"⏳ До Нового года:\n"
        f"{days} дн. {hours} ч. {minutes} мин. {seconds} сек."
    )